#!/usr/bin/env node
// Check File Size ratchets the 2200-line `max-lines` target from .oxlintrc.json.
//
// oxlint already reports `max-lines`, but it runs in the known-red lint lane,
// which only warns, so oversize files kept growing unnoticed. This check is the
// blocking half: it runs in the green "policy guards" lane, where any failure
// is a real regression.
//
// The list is git-tracked files only, the same scope as check-dir-size.mjs
// (src/ and extensions/*/src), tests excluded because oxlint exempts them too.
//
// Files already over the limit are grandfathered in
// config/file-size-grandfather.json at the line count they were at. That count
// is the ratchet: growing past it fails, shrinking below it warns so the max can
// be tightened, and dropping to the limit makes the entry prunable.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const configPath = path.join(repoRoot, "config", "file-size-grandfather.json");

const TEST_FILE_PATTERN = /(?:\.test|\.e2e\.test|\.test-helpers?)\.[cm]?[tj]sx?$/;
const SOURCE_FILE_PATTERN = /\.[cm]?[tj]sx?$/;
const SCANNED_DIR_PATTERN = /^(?:src\/|extensions\/[^/]+\/src\/|ui\/src\/)/;
// Locale bundles are regenerated by `pnpm ui:i18n:sync`; their length tracks the
// key count, not design debt, and oxlint exempts them for the same reason.
const GENERATED_FILE_PATTERN = /^ui\/src\/i18n\/locales\/[^/]+\.ts$/;

/**
 * True for a tracked source file in scope.
 */
export function isScannedSourcePath(repoPath) {
  return (
    SCANNED_DIR_PATTERN.test(repoPath) &&
    SOURCE_FILE_PATTERN.test(repoPath) &&
    !TEST_FILE_PATTERN.test(repoPath) &&
    !GENERATED_FILE_PATTERN.test(repoPath)
  );
}

/**
 * Counts lines the way an editor does: a trailing newline does not open a line.
 */
export function countLines(text) {
  if (text.length === 0) {
    return 0;
  }
  const newlines = text.split("\n").length - 1;
  return text.endsWith("\n") ? newlines : newlines + 1;
}

/**
 * Applies the limit and the grandfather ratchet to a file line-count map.
 *
 * Pure: the runner does the I/O and the exit code.
 */
export function evaluateFileSizes(counts, config) {
  const failures = [];
  const warnings = [];
  const limit = config.limit;
  const byPath = (left, right) => left[0].localeCompare(right[0]);

  for (const [file, lines] of [...counts].toSorted(byPath)) {
    if (lines <= limit) {
      continue;
    }
    const entry = config.grandfathered[file];
    if (!entry) {
      failures.push({
        file,
        detail: `${lines} lines (limit ${limit}); split it into modules, or grandfather it in config/file-size-grandfather.json with a reason`,
      });
      continue;
    }
    if (lines > entry.max) {
      failures.push({
        file,
        detail: `grew to ${lines} lines; grandfathered at ${entry.max}. The grandfather list is a ratchet — extract code before adding more`,
      });
    }
  }

  for (const [file, entry] of Object.entries(config.grandfathered).toSorted(byPath)) {
    const lines = counts.get(file);
    if (lines === undefined || lines <= limit) {
      warnings.push({
        file,
        detail: `${lines === undefined ? "no longer exists" : `now at ${lines} lines (limit ${limit})`}; prune it from config/file-size-grandfather.json`,
      });
      continue;
    }
    if (lines < entry.max) {
      warnings.push({
        file,
        detail: `down to ${lines} from the grandfathered ${entry.max}; tighten the max in config/file-size-grandfather.json to hold the gain`,
      });
    }
  }

  return { failures, warnings };
}

/**
 * Reads and shallowly validates the grandfather config.
 */
export function parseFileSizeConfig(raw) {
  const parsed = JSON.parse(raw);
  if (typeof parsed?.limit !== "number" || !Number.isInteger(parsed.limit) || parsed.limit <= 0) {
    throw new TypeError("config/file-size-grandfather.json must declare a positive integer limit");
  }
  if (typeof parsed.grandfathered !== "object" || parsed.grandfathered === null) {
    throw new TypeError("config/file-size-grandfather.json must declare a grandfathered object");
  }
  for (const [file, entry] of Object.entries(parsed.grandfathered)) {
    if (typeof entry?.max !== "number" || !Number.isInteger(entry.max)) {
      throw new TypeError(`config/file-size-grandfather.json: ${file} must declare an integer max`);
    }
    if (typeof entry.reason !== "string" || entry.reason.length === 0) {
      throw new TypeError(`config/file-size-grandfather.json: ${file} must declare a reason`);
    }
  }
  return parsed;
}

function listTrackedSources() {
  const stdout = execFileSync("git", ["ls-files", "-z", "--", "src", "extensions", "ui/src"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return stdout.split("\0").filter((entry) => entry.length > 0 && isScannedSourcePath(entry));
}

/**
 * Line counts for every tracked in-scope source file.
 */
export function measureTrackedSources() {
  const counts = new Map();
  for (const file of listTrackedSources()) {
    counts.set(file, countLines(readFileSync(path.join(repoRoot, file), "utf8")));
  }
  return counts;
}

function main() {
  const config = parseFileSizeConfig(readFileSync(configPath, "utf8"));
  const counts = measureTrackedSources();
  const { failures, warnings } = evaluateFileSizes(counts, config);
  const overLimit = [...counts.values()].filter((lines) => lines > config.limit).length;

  console.log(
    `File size check: ${counts.size} files, ${overLimit} over the ${config.limit}-line limit, ` +
      `${Object.keys(config.grandfathered).length} grandfathered, ${failures.length} failure(s), ${warnings.length} warning(s).`,
  );

  for (const warning of warnings) {
    console.error(`[file-size] WARNING ${warning.file}: ${warning.detail}`);
  }
  if (failures.length === 0) {
    return 0;
  }
  console.error("\nFile size violations:");
  for (const failure of failures) {
    console.error(`  ${failure.file}\n    ${failure.detail}`);
  }
  return 1;
}

if (import.meta.main) {
  process.exitCode = main();
}
