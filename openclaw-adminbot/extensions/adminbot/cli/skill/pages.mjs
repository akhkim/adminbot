const METHODS = new Set(["get", "post", "put", "patch", "delete"]);

export function renderPages(spec) {
  const groups = new Map(PAGES.map(([title]) => [title, []]));
  const unmatched = [];
  for (const [path, methods] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      if (!METHODS.has(method)) {
        continue;
      }
      const page = PAGES.find((rule) => rule[3].test(path));
      const dryRun = JSON.stringify(op).includes('"dry_run"');
      const row = `| \`${op.operationId}\` | ${method.toUpperCase()} \`${path}\`${dryRun ? " (dry-run)" : ""} |`;
      if (page) {
        groups.get(page[0]).push(row);
      } else {
        unmatched.push(`${method.toUpperCase()} ${path}`);
      }
    }
  }
  if (unmatched.length) {
    throw new Error(
      `No skill page claims these routes; add a rule to skill/pages.mjs:\n${unmatched.join("\n")}`,
    );
  }
  let out =
    "# AdminBot pages → API operations\n\n" +
    "Generated by skill/pages.mjs from the CLI's OpenAPI document. Do not edit by hand.\n" +
    "Run any row with `adminbot call OPERATION_ID [flags]`; see its flags with `adminbot schema OPERATION_ID`.\n" +
    '"(dry-run)" = the operation takes `dry_run`; the CLI previews unless you add `--live`.\n' +
    "GET = read. POST/PUT/PATCH/DELETE = change something (except `post-guidebook-ask` and `*-preview`, which only read). " +
    "Paths ending in `/run` start a job that may message people.\n";
  for (const [title, site, who] of PAGES) {
    const rows = groups.get(title);
    if (rows.length) {
      out += `\n## ${title}\n\nWebsite: \`${site}\` · Who: ${who}\n\n| Operation ID | Route |\n| --- | --- |\n${rows.toSorted().join("\n")}\n`;
    }
  }
  return out;
}
